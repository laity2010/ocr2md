import {unlockCode} from './v6-auth.test-helper.mjs';
import {chromeExecutable} from './platform.test-helper.mjs';
import assert from 'node:assert/strict';
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {chromium} from 'playwright';
const base=process.env.V6_TEST_BASE || 'http://127.0.0.1:4397';
const fixture='packages/minerujson-md/fixtures/buffetts-alpha.minerujson.md';
const isolated='.v6/tests/v6-save-fix.md';
const evidence='.v6/evidence/save-fix';
const code=unlockCode(readFileSync('.v6/private/editor-token','utf8'));
mkdirSync(evidence,{recursive:true});
const original=readFileSync(fixture);
writeFileSync(isolated,original);
const browser=await chromium.launch({executablePath:chromeExecutable(),headless:true});
try {
 const p=await browser.newPage({viewport:{width:1032,height:768}}),errors=[];
 p.on('pageerror',e=>errors.push(e.message));
 await p.goto(base+'/',{waitUntil:'domcontentloaded'});
 await p.waitForFunction(()=>document.querySelector('#status')?.textContent.includes('保存需授权'),{timeout:25000});
 const build=(await p.locator('#build-version').innerText()).trim();
 assert.match(build,/^v6-\d{8}-\d{6}$/);
 assert.equal(await p.locator('#build-version + #status').count(),1,'Global status is not directly after build badge');
 const unauth=await p.evaluate(async()=>{
  const r=await fetch('/api/document',{method:'PUT',body:'bad',headers:{'Content-Type':'text/plain'}});
  return {status:r.status,body:await r.text()};
 });
 assert.equal(unauth.status,403);
 await p.locator('#save').click();
 assert(await p.locator('#unlock-dialog').evaluate(el=>el.open),'Missing unlock dialog');
 await p.locator('#unlock-code').fill('incorrect-code');
 await p.locator('#unlock-form button[type=submit]').click();
 await p.waitForFunction(()=>document.querySelector('#unlock-error')?.textContent.includes('授权码不匹配'),{timeout:10000});
 assert.match(await p.locator('#unlock-error').innerText(),/授权码不匹配/);
 await p.locator('#unlock-code').fill(code);
 await p.locator('#unlock-form button[type=submit]').click();
 await p.waitForFunction(()=>document.querySelector('#status')?.textContent.includes('已保存'),{timeout:20000});
 assert.equal(await p.locator('#unlock-dialog').evaluate(el=>el.open),false);
 assert.equal(await p.evaluate(async()=> (await(await fetch('/api/session')).json()).canSave),true);
 assert.deepEqual(readFileSync(isolated),original, 'Unauthorized/save unchanged roundtrip changed document');
 await p.locator('.cm-content').click({position:{x:90,y:112}});
 await p.keyboard.type('TEST-V6-SAVE-FIX');
 await p.waitForFunction(()=>document.querySelector('#status')?.textContent.includes('未保存'));
 const scroll=await p.locator('.cm-scroller').evaluate(el=>el.scrollTop);
 await p.locator('#save').click();
 await p.waitForFunction(()=>document.querySelector('#status')?.textContent.includes('已保存'),{timeout:20000});
 const afterScroll=await p.locator('.cm-scroller').evaluate(el=>el.scrollTop);
 assert(Math.abs(scroll-afterScroll)<2,'Save changed CM6 scroll');
 const stored=readFileSync(isolated,'utf8');
 assert(stored.includes('TEST-V6-SAVE-FIX'),'Edited document did not persist');
 await p.reload();
 await p.waitForFunction(()=>document.querySelector('#status')?.textContent.includes('已加载'),{timeout:25000});
 assert((await p.locator('.cm-content').innerText()).includes('TEST-V6-SAVE-FIX'),'Reopen lost saved edit');
 await p.screenshot({path:`${evidence}/ipad-viewport.png`,fullPage:true});
 await p.setViewportSize({width:1440,height:900});
 await p.screenshot({path:`${evidence}/desktop.png`,fullPage:true});
 assert.deepEqual(errors,[]);
 console.log('UI_PUBLIC_SAVE_FLOW_PASS',JSON.stringify({build,unauthorizedPUT:unauth.status,wrongCodeRejected:true,unlockAndRetry:true,editedSave:true,afterReload:true,scrollPreserved:true,jsErrors:0,evidence}));
} finally {await browser.close();}
