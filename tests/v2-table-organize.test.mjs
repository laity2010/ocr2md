import assert from 'node:assert/strict';
import {EditorState,ChangeSet} from '@codemirror/state';
import {composeOwnedSource} from '../ui/v2-block-source.js';
import {planMdLineEdit} from '../ui/v2-md-line-edit.js';
import {createMdLineIndex} from '../ui/v2-md-line-index.js';
import {planV2TableOrganization} from '../ui/v2-table-view.js';
const root=1;
const rows=[['table','\n'],['table_caption','Table 3. Caption\n'],['table_body','<table><tr><td><eq>^{a}</eq></td></tr></table>\n'],['text','<sup>a</sup>Notes\n\n'],['text','unrelated\n\n']].map(([blockType,markdownText],i)=>({logicalId:i+1,baseBlockId:i+1,logicalOrder:i+1,p:0,b:i===4?1:0,s:i===4?0:i,parentId:i===0||i===4?null:root,blockType,markdownText}));
const logical=rows.map(r=>({logical_id:r.logicalId,parent_id:r.parentId,block_type:r.blockType}));
const original=composeOwnedSource(rows),doc=EditorState.create({doc:original.source}).doc,index=createMdLineIndex(doc,original.blocks);
const updates=planV2TableOrganization(index,logical,4);
assert.equal(updates.length,3);
const changes=ChangeSet.of(updates.map(u=>{const l=index.resolve(u.ref);assert.equal(u.beforeText,l.md_line);return {from:l.from,to:l.textTo,insert:u.afterText};}),doc.length);
const plan=planMdLineEdit(doc,original.blocks,changes);
assert(plan);assert.deepEqual(plan.blocks.map(r=>r.markdownText),['\n','>Table 3. Caption\n','><!-- image -->\n>>[! ds-html]- HTML Table\n>><table><tr><td><eq>^{a}</eq></td></tr></table>\n','><sup>a</sup>Notes\n\n','unrelated\n\n']);
assert.deepEqual(plan.blocks.map(r=>r.logicalId),rows.map(r=>r.logicalId));
const next=createMdLineIndex(EditorState.create({doc:plan.source}).doc,plan.blocks);
assert.deepEqual(planV2TableOrganization(next,logical,root),[]);
assert.throws(()=>planV2TableOrganization(index,logical,5));
assert.throws(()=>planV2TableOrganization(index,logical.map(r=>r.logical_id===4?{...r,block_type:'table_body'}:r),3));
console.log('WP30C_TABLE_ORGANIZE_DIRECT_PASS');
