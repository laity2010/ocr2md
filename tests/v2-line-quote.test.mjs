import assert from 'node:assert/strict';
import {EditorState,ChangeSet} from '@codemirror/state';
import {composeOwnedSource} from '../ui/v2-block-source.js';
import {createMdLineIndex} from '../ui/v2-md-line-index.js';
import {planMdLineEdit} from '../ui/v2-md-line-edit.js';
import {captureLineSelection,quoteLineChanges} from '../ui/v2-line-quote.js';
const original=composeOwnedSource(['A\n>B\n\n','>>C😀\nD\n\n'].map((markdownText,i)=>({logicalId:i+1,baseBlockId:i+1,logicalOrder:i+1,p:0,b:i,s:0,parentId:null,blockType:'text',markdownText})));
const doc=EditorState.create({doc:original.source}).doc,index=createMdLineIndex(doc,original.blocks);
const select=(from,to)=>captureLineSelection(doc,index,{from,to});
const one=select(1,1);assert.deepEqual([one.first,one.last,one.count],[1,1,1]);
const r=select(1,doc.line(5).from);assert.deepEqual([r.first,r.last,r.count],[1,4,4]);
const changes=quoteLineChanges(index,r,'add');assert.equal(changes.length,4);
const plan=planMdLineEdit(doc,original.blocks,ChangeSet.of(changes,doc.length));
assert.deepEqual(plan.blocks.map(b=>b.markdownText),['>A\n>>B\n>\n\n','>>>C😀\nD\n\n']);
assert.deepEqual(quoteLineChanges(index,r,'remove').map(x=>x.from),[doc.line(2).from,doc.line(4).from]);
assert.deepEqual(quoteLineChanges(index,one,'remove'),[]);
const whole=select(0,doc.length);assert.equal(whole.count,index.rows.length);
const eof=select(doc.length,doc.length);assert.equal(eof.refs.length,0);
assert.throws(()=>quoteLineChanges(createMdLineIndex(doc,original.blocks),r,'add'),/失效/);
