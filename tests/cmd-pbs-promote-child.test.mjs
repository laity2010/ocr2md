import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {toMarkdown,toMineruJSON} from '../packages/minerujson-md/dist/index.js';
import {readCMDBlockChains,planCMDPromotePBSChild,projectCMDBlockTable} from '../ui/cmd-block-chains.js';
import {inspectCMDTextBlocks,queryCMDLayout} from '../ui/cmd-text-blocks.js';
const raw=readFileSync('packages/minerujson-md/fixtures/buffetts-alpha.mineru.json','utf8');
const source=toMarkdown(raw);
const plan=planCMDPromotePBSChild(source,'p1b3s0');
assert.equal(plan.newId,'p1b14');assert.equal(plan.origin,'p1b3s0');
assert.equal(plan.edits.length,2);
for(const e of plan.edits)assert.equal(source.slice(e.from,e.to),e.expected);
const changed=[...plan.edits].sort((a,b)=>b.from-a.from).reduce((s,e)=>s.slice(0,e.from)+e.insert+s.slice(e.to),source);
const newTag='<!-- cmd:block:v1 id="p1b14" origin="p1b3s0" -->';
assert(changed.includes(newTag));assert(!changed.includes('<!-- cmd:block:v1 id="p1b3s0" -->'));
const pageEnd=changed.indexOf('<!-- minerujson:page:v1:2');
const tagPos=changed.indexOf(newTag);assert(tagPos>changed.indexOf('<!-- cmd:block:v1 id="p1b13"')&&tagPos<pageEnd);
assert(changed.slice(tagPos,pageEnd).includes('![image]('));
assert.equal(toMineruJSON(changed),raw);
const current=readCMDBlockChains(changed);assert.equal(current.invalid.length,0);assert.equal(current.atoms.length,267);
const promoted=current.atoms.find(a=>a.id==='p1b14');assert.equal(promoted?.origin,'p1b3s0');assert.equal(promoted?.kind,'parent');
const report=await inspectCMDTextBlocks(changed),layout=await queryCMDLayout(changed);
const projection=projectCMDBlockTable(changed,report.rows,layout,current,report.children);
const row=projection.rows.find(a=>a.id==='p1b14');
assert(row&&row.geometry&&row.origin==='p1b3s0'&&row.kind==='parent');
assert(row.text.includes('![image]'));
assert.equal(projection.rows.filter(a=>a.id==='p1b3s0').length,0);
assert.equal(projection.summary.parents,225);assert.equal(projection.summary.children,42);
assert.throws(()=>planCMDPromotePBSChild(source,'p1b3'),/original direct child/);
assert.throws(()=>planCMDPromotePBSChild(changed,'p1b3s0'),/original direct child/);
assert.equal(source.slice(source.indexOf('<!-- minerujson:source:v1:')),
 changed.slice(changed.indexOf('<!-- minerujson:source:v1:')));
console.log('PBS_CHILD_PROMOTION_PASS',{source:'p1b3s0',newId:'p1b14',atomCount:267,originalJsonExact:true,sourceMoved:true});
