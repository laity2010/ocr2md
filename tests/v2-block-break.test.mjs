import assert from 'node:assert/strict';
import {EditorState} from '@codemirror/state';
import {composeOwnedSource} from '../ui/v2-block-source.js';
import {createMdLineIndex} from '../ui/v2-md-line-index.js';
import {createBreakSession,resolveBreakPair,breakColumns} from '../ui/v2-block-break.js';
const block=(id,s,markdownText,b=0,type='text')=>({logicalId:id,baseBlockId:id,logicalOrder:id,parentId:s?1:null,p:0,b,s,blockType:type,markdownText});
const make=rows=>{const c=composeOwnedSource(rows);return createMdLineIndex(EditorState.create({doc:c.source}).doc,c.blocks);};
const idx=make([block(1,0,'Some invest-\n'),block(2,1,'ment continues.\n\n'),block(3,0,'Other paragraph.\n\n',1)]);
const session=createBreakSession();
let rows=session.project(idx);assert.equal(rows.length,1);
const first=rows[0];assert.equal(first.kind,'跨块断词');assert.equal(first.review,'待定');
assert.equal(resolveBreakPair(idx,first).length,2);
session.choose(idx,first,'忽略');rows=session.project(idx);assert.equal(rows[0].review,'忽略');
assert.throws(()=>session.choose(idx,first,'断块合并'),/过期/);
const result=session.choose(idx,rows[0],'断块合并');
assert.equal(result.updates[0].afterText,'Some investment continues.');
assert.equal(result.updates[1].afterText,'');
const merged=make([block(1,0,'Some investment continues.\n'),block(2,1,'\n\n'),block(3,0,'Other paragraph.\n\n',1)]);
session.accept(result.receipt);assert.equal(session.project(merged)[0].merged,true);
assert.equal(session.project(idx)[0].review,'待定');
assert.equal(session.project(merged)[0].merged,true);
assert.equal(createBreakSession().project(merged).length,0);
assert.equal(resolveBreakPair(merged,first),null);
const gap=make([block(1,0,'Some invest-\n\n'),block(2,1,'ment continues.\n\n')]);
const g=createBreakSession();assert.throws(()=>g.choose(gap,g.project(gap)[0],'断块合并'),/不相邻/);
assert.equal(breakColumns(null)[0].pinned,'left');assert.equal(breakColumns(null)[2].pinned,'right');
console.log('WP28_BREAK_DIRECT_PASS');
